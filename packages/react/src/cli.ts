/**
 * Build-time artefacts for the react package.
 *
 * 1. dist/styles.css: the component stylesheets concatenated in order.
 *    Shipping one stylesheet rather than importing CSS from the TSX means
 *    consumers need no bundler configuration for CSS, and the library stays
 *    usable from plain HTML.
 *
 * 2. dist/manifest.js: each component's source and stylesheet, embedded.
 *    The MCP server's get_component tool answers from this. It is generated
 *    at build time rather than read from src at runtime, because once the
 *    package is published src may not ship and relative paths do not survive.
 *    The cost is a rebuild to refresh, which is the lesser problem.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const srcDir = join(here, '..', 'src');

/** The shared rules every component relies on, outside any component folder. */
const FOUNDATIONS_CSS = 'styles/foundations.css';

/**
 * Component name. Each component lives in components/<Name>/ with its
 * source at <Name>.tsx and its stylesheet at <Name>.css.
 * NostalgiaRoot is listed because every other component needs it as an
 * ancestor, so an agent asking for a Button must also be told about the root.
 */
export const COMPONENTS = ['NostalgiaRoot', 'Button', 'Input', 'Card', 'Tabs', 'Dialog'] as const;

const componentFile = (name: string, extension: string): string =>
  'components/' + name + '/' + name + extension;

/**
 * Stylesheets in concatenation order, relative to src. The root rule comes
 * first and the shared foundation second, which is the order they had when
 * both lived in one base.css, so dist/styles.css resolves exactly as before.
 */
export const STYLE_ORDER = [
  componentFile('NostalgiaRoot', '.css'),
  FOUNDATIONS_CSS,
  ...COMPONENTS.filter((name) => name !== 'NostalgiaRoot').map((name) =>
    componentFile(name, '.css'),
  ),
] as const;

// --- styles.css ------------------------------------------------------------

const styleParts: string[] = [
  '/*',
  ' * NostalgiaUI component styles. Generated by packages/react. Do not edit.',
  ' *',
  ' * Requires the token layer: import @nostalgiaui/tokens/tokens.css first,',
  ' * then set data-era and data-palette on an ancestor element.',
  ' */',
  '',
];

for (const path of STYLE_ORDER) {
  styleParts.push(await readFile(join(srcDir, path), 'utf8'));
}

await writeFile(join(here, 'styles.css'), styleParts.join('\n'), 'utf8');
process.stdout.write('wrote styles.css from ' + String(STYLE_ORDER.length) + ' stylesheets\n');

// --- manifest.js -----------------------------------------------------------

interface ManifestEntry {
  readonly name: string;
  readonly source: string;
  readonly stylesheet: string;
  readonly css: string;
}

const entries: ManifestEntry[] = [];
for (const name of COMPONENTS) {
  const own = await readFile(join(srcDir, componentFile(name, '.css')), 'utf8');
  // The root's entry also carries the shared foundation, so an agent that
  // reads NostalgiaRoot first (as get_component tells it to) still receives
  // the focus and motion rules every component depends on.
  const css =
    name === 'NostalgiaRoot'
      ? own + '\n' + (await readFile(join(srcDir, FOUNDATIONS_CSS), 'utf8'))
      : own;
  entries.push({
    name,
    source: await readFile(join(srcDir, componentFile(name, '.tsx')), 'utf8'),
    stylesheet: name + '.css',
    css,
  });
}

const manifestJs = [
  '// NostalgiaUI component manifest. Generated by packages/react. Do not edit.',
  'export const manifest = ' + JSON.stringify(entries, null, 2) + ';',
  '',
].join('\n');

const manifestDts = [
  'export interface ManifestEntry {',
  '  readonly name: string;',
  '  readonly source: string;',
  '  readonly stylesheet: string;',
  '  readonly css: string;',
  '}',
  'export declare const manifest: readonly ManifestEntry[];',
  '',
].join('\n');

await writeFile(join(here, 'manifest.js'), manifestJs, 'utf8');
await writeFile(join(here, 'manifest.d.ts'), manifestDts, 'utf8');
process.stdout.write('wrote manifest.js with ' + String(entries.length) + ' components\n');
