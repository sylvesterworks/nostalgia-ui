/**
 * Concatenate the component stylesheets into one dist/styles.css.
 *
 * Shipping a single stylesheet rather than importing CSS from the TSX means
 * consumers need no bundler configuration for CSS, and the library stays
 * usable from plain HTML. The order matters: base first, then components.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const sourceDir = join(here, '..', 'src', 'styles');
const outFile = join(here, 'styles.css');

export const STYLE_ORDER = [
  'base.css',
  'button.css',
  'input.css',
  'card.css',
  'tabs.css',
  'dialog.css',
] as const;

const parts: string[] = [
  '/*',
  ' * NostalgiaUI component styles. Generated by packages/react. Do not edit.',
  ' *',
  ' * Requires the token layer: import @nostalgiaui/tokens/tokens.css first,',
  ' * then set data-era and data-palette on an ancestor element.',
  ' */',
  '',
];

for (const name of STYLE_ORDER) {
  parts.push(await readFile(join(sourceDir, name), 'utf8'));
}

await writeFile(outFile, parts.join('\n'), 'utf8');
process.stdout.write('wrote styles.css from ' + String(STYLE_ORDER.length) + ' stylesheets\n');
