import { eras } from './eras/index.js';
import { palettes } from './palettes/index.js';
import { toSemantic } from './semantic.js';
import type { Era, Palette, SemanticColors } from './types.js';

export const PREFIX = '--nui';

const kebab = (value: string): string => value.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase());

function block(selector: string, lines: readonly string[]): string {
  return [selector + ' {', ...lines.map((line) => '  ' + line), '}'].join('\n');
}

function colorVars(semantic: SemanticColors): string[] {
  return Object.entries(semantic).map(
    ([key, value]) => PREFIX + '-color-' + kebab(key) + ': ' + value + ';',
  );
}

function shapeVars(era: Era): string[] {
  return Object.entries(era.shape).map(
    ([key, value]) => PREFIX + '-' + kebab(key) + ': ' + value + ';',
  );
}

function derivedVars(era: Era, semantic: SemanticColors): string[] {
  return Object.entries(era.derive(semantic)).map(
    ([key, value]) => PREFIX + '-era-' + key + ': ' + value + ';',
  );
}

/**
 * Colour only. One block per palette, keyed on the data-palette attribute.
 * Nothing in this file can describe shape, because it is generated from the
 * semantic colours and nothing else.
 */
export function emitPalettesCss(): string {
  const header = [
    '/*',
    ' * NostalgiaUI palettes. Generated by packages/tokens. Do not edit.',
    ' *',
    ' * Colour only. A palette never sets radius, border, font or motion.',
    ' */',
    '',
  ].join('\n');

  const blocks = palettes.map((palette) =>
    block('[data-palette="' + palette.id + '"]', colorVars(toSemantic(palette))),
  );

  return header + blocks.join('\n\n') + '\n';
}

/**
 * Shape only. One block per era, keyed on the data-era attribute. Generated
 * from era.shape, which has no field capable of holding a colour.
 */
export function emitErasCss(): string {
  const header = [
    '/*',
    ' * NostalgiaUI eras. Generated by packages/tokens. Do not edit.',
    ' *',
    ' * Shape only. An era never sets a colour here; colours an era needs are',
    ' * derived per pairing in pairings.css.',
    ' */',
    '',
  ].join('\n');

  const blocks = eras.map((era) => block('[data-era="' + era.id + '"]', shapeVars(era)));

  return header + blocks.join('\n\n') + '\n';
}

/**
 * The cross product, and the only generated file that mentions both axes.
 *
 * An era's derived colours are a function of the palette's semantic colours,
 * so a 90s bevel highlight cannot be known until both axes are chosen. The
 * SOURCE files stay independent (an era declares a recipe, a palette declares
 * colour); the build evaluates the recipes. Adding a palette regenerates this
 * file and touches no era source.
 */
export function emitPairingsCss(): string {
  const header = [
    '/*',
    ' * NostalgiaUI era/palette pairings. Generated by packages/tokens.',
    ' * Do not edit.',
    ' *',
    ' * Era colour recipes evaluated against each palette. ' +
      String(eras.length) +
      ' eras x ' +
      String(palettes.length) +
      ' palettes.',
    ' */',
    '',
  ].join('\n');

  const blocks: string[] = [];
  for (const palette of palettes) {
    const semantic = toSemantic(palette);
    for (const era of eras) {
      blocks.push(
        block(
          '[data-palette="' + palette.id + '"][data-era="' + era.id + '"]',
          derivedVars(era, semantic),
        ),
      );
    }
  }

  return header + blocks.join('\n\n') + '\n';
}

interface DtcgToken {
  readonly $type: string;
  readonly $value: string;
}

type DtcgGroup = { [key: string]: DtcgGroup | DtcgToken };

/** W3C Design Tokens format, which is the hand-off point for other tooling. */
export function emitDtcg(): string {
  const colorGroup: DtcgGroup = {};
  for (const palette of palettes) {
    const group: DtcgGroup = {};
    for (const [key, value] of Object.entries(toSemantic(palette))) {
      group[kebab(key)] = { $type: 'color', $value: value };
    }
    colorGroup[palette.id] = group;
  }

  const shapeGroup: DtcgGroup = {};
  for (const era of eras) {
    const group: DtcgGroup = {};
    for (const [key, value] of Object.entries(era.shape)) {
      group[kebab(key)] = { $type: 'other', $value: value };
    }
    shapeGroup[era.id] = group;
  }

  const pairingGroup: DtcgGroup = {};
  for (const palette of palettes) {
    const semantic = toSemantic(palette);
    for (const era of eras) {
      const group: DtcgGroup = {};
      for (const [key, value] of Object.entries(era.derive(semantic))) {
        group[key] = { $type: 'other', $value: value };
      }
      pairingGroup[palette.id + '--' + era.id] = group;
    }
  }

  return (
    JSON.stringify({ palette: colorGroup, era: shapeGroup, pairing: pairingGroup }, null, 2) + '\n'
  );
}

/** A Tailwind preset mapping utility names onto the CSS variables above. */
export function emitTailwindPreset(): string {
  const colorKeys = Object.keys(toSemantic(palettes[0] ?? throwNoPalette()));
  const colors = Object.fromEntries(
    colorKeys.map((key) => [kebab(key), 'var(' + PREFIX + '-color-' + kebab(key) + ')']),
  );
  const radius = ['none', 'sm', 'md', 'lg', 'pill'];
  const borderRadius = Object.fromEntries(
    radius.map((key) => [
      key,
      'var(' + PREFIX + '-radius' + (key === 'none' ? '-none' : '-' + key) + ')',
    ]),
  );

  return [
    '// NostalgiaUI Tailwind preset. Generated by packages/tokens. Do not edit.',
    '//',
    '// Utilities resolve to CSS variables, so switching data-era or',
    '// data-palette restyles Tailwind-built markup with no rebuild.',
    'export default ' +
      JSON.stringify({ theme: { extend: { colors, borderRadius } } }, null, 2) +
      ';',
    '',
  ].join('\n');
}

function throwNoPalette(): Palette {
  throw new Error('No palettes are defined');
}

/**
 * Runtime variable maps, for palettes that were never part of a build.
 *
 * The build emits CSS files for the palettes shipped in this package. A theme
 * imported in the browser cannot go through that path, so these return the
 * same variables as plain records for the caller to apply to an element.
 *
 * Deliberately no DOM here: this package has no DOM types and should stay
 * usable in Node, so applying the result is the caller's job.
 */
export function semanticVars(palette: Palette): Record<string, string> {
  return Object.fromEntries(
    Object.entries(toSemantic(palette)).map(([key, value]) => [
      PREFIX + '-color-' + kebab(key),
      value,
    ]),
  );
}

/** Shape variables for one era. */
export function eraVars(era: Era): Record<string, string> {
  return Object.fromEntries(
    Object.entries(era.shape).map(([key, value]) => [PREFIX + '-' + kebab(key), value]),
  );
}

/** The derived colours for one era and palette pairing. */
export function pairingVars(era: Era, palette: Palette): Record<string, string> {
  return Object.fromEntries(
    Object.entries(era.derive(toSemantic(palette))).map(([key, value]) => [
      PREFIX + '-era-' + key,
      value,
    ]),
  );
}
